create table account_transfer (
    id bigint generated by default as identity primary key,
    public_id uuid not null,
    source_account_id bigint not null references pension_account(id),
    target_account_id bigint references pension_account(id),
    external_target_reference varchar(150),
    amount numeric(19,2) not null,
    status varchar(30) not null,
    failure_code varchar(50),
    created_at timestamptz not null,
    updated_at timestamptz not null,
    version bigint not null default 0,
    constraint uk_transfer_public_id unique(public_id),
    constraint ck_transfer_amount_positive check(amount > 0),
    constraint ck_transfer_one_target check(
        (target_account_id is not null and external_target_reference is null)
        or (target_account_id is null and external_target_reference is not null)
    ),
    constraint ck_transfer_different_accounts check(target_account_id is null or target_account_id <> source_account_id)
);
create index idx_transfer_source_created on account_transfer(source_account_id, created_at desc);
create index idx_transfer_status_created on account_transfer(status, created_at);

