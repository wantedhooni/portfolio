-- Original migration 01: V1__create_contract.sql
-- =====================================================================
create table employer (
    id bigint generated by default as identity primary key,
    public_id uuid not null,
    business_no varchar(20) not null,
    display_name varchar(200) not null,
    created_at timestamptz not null,
    constraint uk_employer_public_id unique(public_id),
    constraint uk_employer_business_no unique(business_no)
);

create table participant (
    id bigint generated by default as identity primary key,
    public_id uuid not null,
    profile_ref varchar(100) not null,
    status varchar(20) not null,
    created_at timestamptz not null,
    constraint uk_participant_public_id unique(public_id),
    constraint uk_participant_profile_ref unique(profile_ref)
);

create table plan_contract (
    id bigint generated by default as identity primary key,
    public_id uuid not null,
    contract_no varchar(80) not null,
    employer_id bigint references employer(id),
    plan_type varchar(10) not null,
    status varchar(20) not null,
    effective_at timestamptz not null,
    constraint uk_plan_contract_public_id unique(public_id),
    constraint uk_plan_contract_no unique(contract_no),
    constraint ck_plan_type check(plan_type in ('DB','DC','IRP'))
);
create index idx_contract_employer on plan_contract(employer_id);

