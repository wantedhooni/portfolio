create table pension_account (
    id bigint generated by default as identity primary key,
    public_id uuid not null,
    contract_id bigint not null references plan_contract(id),
    participant_id bigint not null references participant(id),
    status varchar(30) not null,
    cash_balance numeric(19,2) not null default 0,
    reserved_cash numeric(19,2) not null default 0,
    version bigint not null default 0,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    constraint uk_pension_account_public_id unique(public_id),
    constraint uk_pension_account_contract_participant unique(contract_id, participant_id),
    constraint ck_account_cash_nonnegative check(cash_balance >= 0),
    constraint ck_account_reserved_nonnegative check(reserved_cash >= 0),
    constraint ck_account_reserved_lte_cash check(cash_balance >= reserved_cash)
);
create index idx_account_contract on pension_account(contract_id);
create index idx_account_participant on pension_account(participant_id);

